// MubeenFlutterPlugin.swift
//
// Reconciled against Pigeon 29.0.2 generated output (`Messages.g.swift`). Compiled and
// unit-tested on macOS CI, which builds the example for the simulator and runs the
// plugin's XCTest suite (example/ios/RunnerTests/RunnerTests.swift), and run on real
// iPhones through a device farm.
//
// IF A FUTURE CHANGE FAILS TO COMPILE, CHECK THESE FIRST, IN THIS ORDER:
//   1. Access level. Pigeon generates `MubeenHostApi`, `MbConfig`, `MbCapabilities`,
//      `MbError`, `PigeonError` et al as INTERNAL. A `public` method whose signature
//      mentions one of them is an error ("cannot be declared public because its ...
//      uses an internal type"). That is why only `register(with:)` and
//      `detachFromEngine(for:)` are public here; every `MubeenHostApi` witness is
//      internal on purpose. Do not "fix" a visibility error by adding `public`.
//   2. Async-vs-completion drift. Pigeon 29 emits `async throws` protocol requirements.
//      If pigeon is re-run at a different version and reverts to completion handlers,
//      every witness below changes shape again.
//   3. Actor isolation. The generated `setUp` invokes each async requirement from
//      `Task { @MainActor in ... }`. The requirements themselves are NOT isolated and
//      this class carries no global actor, so every witness is nonisolated-async and
//      hops OFF the platform thread on entry (SE-0338). The blocking SDK work below
//      depends on that; if an isolation annotation is ever added to this class, the
//      collection path starts blocking the platform thread.
//   4. `Sendable` diagnostics under Swift 6 mode around `report(_:)` — see its comment —
//      and around the process-wide state boxes (`SharedConfigState`, `MubeenErrorRelay`),
//      which are `@unchecked Sendable` and guard every field with their own lock.
//   5. The SDK symbol names (`MubeenSDKError` cases, `LogLevel` cases, `MubeenConfig`
//      init labels). Those come from a binary xcframework and can drift on an SDK bump.
//
// In-repo path: ios/mubeen_flutter/Sources/mubeen_flutter/MubeenFlutterPlugin.swift
// (Flutter's SPM-compatible plugin layout; the CocoaPods podspec points at the
// same directory — see mubeen_flutter.podspec.)
//
// `Messages.g.swift` is generated by pigeon from pigeons/messages.dart and is NOT
// written by hand. It supplies: MubeenHostApi, MubeenHostApiSetup, MubeenFlutterApi,
// MbConfig, MbLinkage, MbFingerprintRequest, MbError, MbCapabilities, MbLogLevel,
// and PigeonError.

import Flutter
import Foundation
import MubeenDeviceSDK

// Pigeon >= 22 names its Swift error type `PigeonError`. Earlier generators emitted a
// Swift class literally named `FlutterError` inside Messages.g.swift (which shadowed
// Flutter's own). If you ever pin an older pigeon, this alias is the only line to change.
// `wrapError` (Messages.g.swift:36) unpacks PigeonError and FlutterError identically, so
// either type reaches Dart as a code/message/details triple; anything else arrives as a
// stringified Swift type name instead of a contract code.
typealias MbHostError = PigeonError

public final class MubeenFlutterPlugin: NSObject, FlutterPlugin, MubeenHostApi,
                                        @unchecked Sendable {

    // MARK: - Registration
    //
    // One plugin instance per Flutter engine (the app's UI engine, add-to-app engines,
    // background-isolate engines), but ONE native SDK per process. So the configure state
    // and the SDK delegate are process-wide (`SharedConfigState`, `MubeenErrorRelay`), and
    // each instance only contributes its engine's channel to them.

    public static func register(with registrar: FlutterPluginRegistrar) {
        let messenger = registrar.messenger()
        let instance = MubeenFlutterPlugin(
            flutterApi: MubeenFlutterApi(binaryMessenger: messenger)
        )
        MubeenHostApiSetup.setUp(binaryMessenger: messenger, api: instance)
        // MubeenHostApiSetup does not retain the api, and the relay holds instances
        // weakly. `publish` ties the instance's lifetime to the engine.
        registrar.publish(instance)
        MubeenErrorRelay.shared.attach(instance)
    }

    /// Called by the engine when it goes away. Only this engine's entry is removed:
    /// the other engines keep receiving async SDK errors.
    public func detachFromEngine(for registrar: FlutterPluginRegistrar) {
        MubeenHostApiSetup.setUp(binaryMessenger: registrar.messenger(), api: nil)
        MubeenErrorRelay.shared.detach(self)
    }

    // MARK: - Init

    private let flutterApi: MubeenFlutterApi?
    /// Test seam: receives async errors instead of `flutterApi`.
    private let errorSink: (@MainActor (MbError) -> Void)?

    /// - Parameters:
    ///   - flutterApi: nil in unit tests, where there is no binary messenger.
    ///   - errorSink: unit tests only; when set, async errors go here instead.
    init(flutterApi: MubeenFlutterApi?, errorSink: (@MainActor (MbError) -> Void)? = nil) {
        self.flutterApi = flutterApi
        self.errorSink = errorSink
        super.init()
    }

    override convenience init() {
        self.init(flutterApi: nil)
    }

    // MARK: - Constants

    /// The SDK's `MubeenConfig.endpoint` is a non-optional `URL` with no default
    /// (MubeenConfig.swift:12), so "null uses the native SDK default" from the Pigeon
    /// contract has to be satisfied here. This is the endpoint the public integration
    /// guide uses (Mubeen-IOS-SDK-public/INTEGRATION.md:17).
    static let defaultEndpoint = "https://fp.sa.mubeen.ai"

    /// The metadata keys the SDK auto-detects and SHA-256 hashes into `linkage`,
    /// verbatim from `SignalCollector.linkageKeys` (SignalCollector.swift:126).
    /// That constant is `internal` to the SDK module, so it cannot be referenced from
    /// here — these four strings are a hand-copy and MUST be re-checked on every SDK
    /// bump. `MubeenFlutterPluginTests.testLinkageKeysUseTheNamesTheSDKHashes` pins them.
    static let linkageKeys: Set<String> = ["account_id", "payment_token_id", "email", "phone"]

    /// `APIClient.fingerprintPath` (APIClient.swift:16) — also internal to the SDK.
    static let fingerprintPath = "/v1/mobile/fingerprint"

    // MARK: - Configure state
    //
    // The iOS SDK does NOT guard re-configuration. `Mubeen.configure` only rejects a
    // *concurrent* call (`beginConfiguring()`, MubeenDeviceSDK.swift:41-46, 73-76); a
    // second sequential call with different values genuinely re-configures and returns
    // success. So the contract's "a differing re-configure must throw" is enforced
    // entirely here, and this snapshot is the only record of what was applied
    // (`Mubeen.config` is private). It is process-wide, like the SDK: a second engine
    // configuring with identical values is a no-op, with different values an error.

    struct ConfigSnapshot: Equatable {
        let apiKey: String
        let endpoint: String
        let logLevel: Int
        /// Only the iOS option group: `MbConfig.android` is ignored on this platform by
        /// design, so a difference there is not a different configuration.
        let ios: MbIosOptions
    }

    enum ConfigState {
        case configuring(ConfigSnapshot)
        case configured(ConfigSnapshot)

        var snapshot: ConfigSnapshot {
            switch self {
            case .configuring(let s), .configured(let s): return s
            }
        }
    }

    /// Every field is guarded by `lock`.
    final class SharedConfigState: @unchecked Sendable {
        let lock = NSLock()
        var state: ConfigState?
        /// Identical configure calls waiting for the in-flight one to finish.
        var waiters: [CheckedContinuation<Void, Error>] = []
    }

    static let configState = SharedConfigState()

    static var isConfigured: Bool {
        let box = MubeenFlutterPlugin.configState
        box.lock.lock(); defer { box.lock.unlock() }
        if case .some(.configured) = box.state { return true }
        return false
    }

    /// Test seam: how many identical configure calls are parked on the in-flight one.
    static var parkedConfigureWaiters: Int {
        let box = MubeenFlutterPlugin.configState
        box.lock.lock(); defer { box.lock.unlock() }
        return box.waiters.count
    }

    /// Test seam: forgets the process-wide configure state and every attached engine.
    static func resetStateForTesting() {
        finishConfigure(with: MbHostError(code: "not_configured", message: "reset", details: nil))
        MubeenErrorRelay.shared.detachAll()
    }

    // MARK: - MubeenHostApi: configure

    /// Initializes the native SDK.
    ///
    /// Re-configure rule (contract): identical values are a no-op success; different
    /// values throw `already_configured` rather than appearing to work. Flutter hot
    /// restart re-runs Dart `main()` but not the host process, which is where this bites.
    ///
    /// Threading: nonisolated async, so awaiting `Mubeen.configure` runs on the generic
    /// executor rather than the platform thread the generated `setUp` calls in on.
    func configure(config: MbConfig) async throws {
        // Throws invalid_config / already_configured, and claims the state slot
        // synchronously before the first await.
        guard let nativeConfig = try beginConfigure(config) else {
            // Identical to a configuration that is applied, or still being applied
            // (possibly by another engine). Succeed only once that one has.
            try await Self.waitUntilConfigured()
            return
        }

        // Set before configuring: `Mubeen.configure` starts a retry drain, and a 429/5xx
        // from it must already have somewhere to go.
        Mubeen.delegate = MubeenErrorRelay.shared
        do {
            try await Mubeen.configure(nativeConfig)
        } catch {
            // Roll the snapshot back so the client can retry with corrected values
            // instead of being permanently locked out by `already_configured`.
            let hostError = Self.hostError(from: error)
            Self.finishConfigure(with: hostError)
            throw hostError
        }
        Self.finishConfigure(with: nil)
    }

    /// Decides what a `configure` call should do, without touching the SDK.
    ///
    /// - Returns: the native config to apply, or `nil` when this is an identical
    ///   re-configure (no-op success).
    /// - Throws: `invalid_config` for an empty api key or an endpoint that is not a
    ///   usable absolute http(s) URL; `already_configured` when values differ from
    ///   what was already applied.
    ///
    /// Internal rather than private so the tests can exercise the whole rule without a
    /// network, a Keychain, or a binary messenger.
    func beginConfigure(_ config: MbConfig) throws -> MubeenConfig? {
        guard !config.apiKey.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else {
            // The SDK throws `configurationInvalid` for this too (MubeenDeviceSDK.swift:79),
            // but only after it has already installed the APIClient. Reject earlier.
            throw MbHostError(
                code: "invalid_config",
                message: "apiKey must not be empty.",
                details: nil
            )
        }

        let endpointString = config.endpoint ?? Self.defaultEndpoint
        // Never force-unwrap: a malformed endpoint from Dart would crash the host app.
        guard let url = URL(string: endpointString),
              let scheme = url.scheme?.lowercased(),
              scheme == "https" || scheme == "http",
              let host = url.host, !host.isEmpty
        else {
            throw MbHostError(
                code: "invalid_config",
                message: "endpoint is not a valid absolute http(s) URL: \"\(endpointString)\".",
                details: nil
            )
        }

        let snapshot = ConfigSnapshot(
            apiKey: config.apiKey,
            endpoint: url.absoluteString,
            logLevel: config.logLevel.rawValue,
            ios: config.ios
        )

        let box = MubeenFlutterPlugin.configState
        box.lock.lock()
        defer { box.lock.unlock() }
        if let existing = box.state {
            guard existing.snapshot == snapshot else {
                throw MbHostError(
                    code: "already_configured",
                    message: "configure() was already called with different values. "
                        + "Re-configuring after the first call is not supported — restart the "
                        + "host process to change it. (Flutter hot restart re-runs Dart main() "
                        + "but not the host process, which is the usual way this is hit.)",
                    details: nil
                )
            }
            return nil
        }
        // Claim the slot synchronously, before any await, so two concurrent configure()
        // calls cannot both reach `Mubeen.configure` (whose own concurrent-call guard
        // returns *success* without configuring — MubeenDeviceSDK.swift:73-76).
        box.state = .configuring(snapshot)

        return MubeenConfig(
            apiKey: config.apiKey,
            endpoint: url,
            // Passed through as-is. The Dart facade sends the SDK's own defaults
            // (production, jailbreak checks ON, behavioral signals off) unless the app
            // changed them. None of these needs an iOS permission.
            environment: Self.environment(from: config.ios.environment),
            enableJailbreakChecks: config.ios.enableJailbreakChecks,
            enableBehavioralSignals: config.ios.enableBehavioralSignals,
            logLevel: Self.logLevel(from: config.logLevel)
        )
    }

    /// Ends the in-flight configure: marks it applied (`error == nil`) or clears it so a
    /// retry is possible, and wakes every identical call waiting on it with the same
    /// outcome.
    static func finishConfigure(with error: Error?) {
        let box = MubeenFlutterPlugin.configState
        box.lock.lock()
        if error != nil {
            box.state = nil
        } else if let state = box.state {
            box.state = .configured(state.snapshot)
        }
        let waiters = box.waiters
        box.waiters = []
        box.lock.unlock()

        for waiter in waiters {
            if let error = error {
                waiter.resume(throwing: error)
            } else {
                waiter.resume()
            }
        }
    }

    /// Returns once the configure that `beginConfigure` found in flight has succeeded,
    /// and throws its error if it failed.
    static func waitUntilConfigured() async throws {
        try await withCheckedThrowingContinuation { (continuation: CheckedContinuation<Void, Error>) in
            let box = MubeenFlutterPlugin.configState
            box.lock.lock()
            switch box.state {
            case .some(.configuring):
                box.waiters.append(continuation)
                box.lock.unlock()
            case .some(.configured):
                box.lock.unlock()
                continuation.resume()
            case .none:
                // The in-flight configure failed between our check and now; its error
                // went to its own caller.
                box.lock.unlock()
                continuation.resume(throwing: MbHostError(
                    code: "not_configured",
                    message: "A concurrent configure() with the same values failed. "
                        + "Call configure() again.",
                    details: nil
                ))
            }
        }
    }

    /// MbLogLevel (contract order: none, error, warning, info, debug) -> SDK LogLevel.
    /// The SDK also has `.verbose`, which the contract does not expose.
    static func logLevel(from level: MbLogLevel) -> LogLevel {
        switch level {
        case .none: return .none
        case .error: return .error
        case .warning: return .warning
        case .info: return .info
        case .debug: return .debug
        }
    }

    static func environment(from environment: MbIosEnvironment) -> MubeenEnvironment {
        switch environment {
        case .production: return .production
        case .sandbox: return .sandbox
        }
    }

    // MARK: - MubeenHostApi: device id

    /// On iOS `Mubeen.deviceId` lazily mints and persists an id on first access, so it
    /// would work before `configure()` (DeviceIDStore.deviceId(), DeviceIDStore.swift:34).
    /// The plugin still requires configure-first so that Android and iOS behave
    /// identically — Android's `getDeviceId()` genuinely needs `init()` first.
    func getDeviceId() async throws -> String {
        guard Self.isConfigured else { throw Self.notConfiguredError() }
        // Reading is a Keychain hit on first access, memory-cached after; no upload is
        // triggered on iOS (there is no `uploadOnGetId` equivalent to override).
        return Mubeen.deviceId
    }

    func resetDeviceId() async throws -> String {
        guard Self.isConfigured else { throw Self.notConfiguredError() }
        return Mubeen.resetDeviceId()
    }

    // MARK: - MubeenHostApi: sendFingerprint

    /// Collects a fingerprint and hands it to the native uploader.
    ///
    /// Returning means **accepted-or-queued, not delivered**:
    ///  * 2xx (200/202/204)            -> success
    ///  * 404/405                      -> throws, code `invalid_config` (wrong route)
    ///  * other 4xx, e.g. 400/401/403  -> throws, code `rejected`
    ///  * 429 / 5xx / offline          -> the SDK enqueues for retry and *returns
    ///    normally* (MubeenDeviceSDK.swift:158-163), so this returns success.
    ///    The only signal is `MubeenFlutterApi.onError`, fed by the SDK delegate below.
    ///  * kill switch on               -> throws, code `disabled`
    func sendFingerprint(request: MbFingerprintRequest) async throws {
        guard Self.isConfigured else { throw Self.notConfiguredError() }
        let metadata = Self.buildMetadata(linkage: request.linkage, custom: request.custom)

        do {
            // Signal collection blocks for a few hundred ms; nonisolated async keeps it
            // off the platform thread.
            try await Mubeen.sendFingerprint(metadata: metadata)
        } catch {
            throw Self.hostError(from: error)
        }
    }

    /// Flattens the typed linkage + custom extras into the `[String: String]` the SDK
    /// takes, using the exact key names it auto-detects and hashes.
    ///
    /// The Dart facade already refuses a `custom` key named like a linkage key, so this
    /// is a second line of defence for callers of the raw channel.
    ///
    /// A `custom` key that collides with a linkage key is **dropped**, not merged: the
    /// SDK strips those four names out of `custom` anyway
    /// (`SignalCollector.customSignals(from:)`, SignalCollector.swift:130-134), so a
    /// colliding custom value would either silently overwrite the typed linkage value or
    /// vanish, depending on merge order. Dropping it makes the typed field authoritative.
    ///
    /// Returns nil when there is nothing to send, which is what the SDK's default is.
    static func buildMetadata(linkage: MbLinkage?, custom: [String: String]?) -> [String: String]? {
        var metadata: [String: String] = [:]

        if let linkage {
            if let v = linkage.accountId { metadata["account_id"] = v }
            if let v = linkage.paymentTokenId { metadata["payment_token_id"] = v }
            if let v = linkage.email { metadata["email"] = v }
            if let v = linkage.phone { metadata["phone"] = v }
        }

        if let custom {
            for (key, value) in custom where !linkageKeys.contains(key) {
                metadata[key] = value
            }
        }

        return metadata.isEmpty ? nil : metadata
    }

    // MARK: - MubeenHostApi: unsupported on iOS

    /// The iOS SDK is one-way submit: `sendFingerprint` encodes and posts internally and
    /// never hands the payload back (MubeenDeviceSDK.swift:144-155). There is no
    /// equivalent of Android's `getFingerprint()`, so this throws rather than
    /// reconstructing an approximation that would not match what was uploaded.
    func getFingerprint() async throws -> String {
        throw Self.unsupported(
            "getFingerprint() is Android-only. The iOS SDK is one-way submit and never "
            + "exposes the collected payload. Branch on capabilities().rawFingerprint."
        )
    }

    /// `RetryQueue.pendingCount` exists (RetryQueue.swift:43) but `RetryQueue` is internal
    /// to the SDK module and the facade exposes nothing. Returning 0 would be a lie that
    /// reads as "queue empty" when it may hold payloads.
    func pendingUploadCount() async throws -> Int64 {
        throw Self.unsupported(
            "pendingUploadCount() is Android-only. The iOS SDK's retry queue is not "
            + "introspectable. Branch on capabilities().pendingUploadCount."
        )
    }

    // MARK: - MubeenHostApi: capabilities

    func capabilities() throws -> MbCapabilities {
        MbCapabilities(
            linkage: true,            // sendFingerprint(metadata:) hashes the four keys
            customData: true,         // non-linkage metadata keys pass through as `custom`
            rawFingerprint: false,    // see getFingerprint above
            pendingUploadCount: false // see pendingUploadCount above
        )
    }

    /// Android-only question. On iOS the device id lives in the Keychain with
    /// `kSecAttrAccessibleAfterFirstUnlockThisDeviceOnly` (SecureStorage.swift:28), which
    /// is not opt-in — there are no backup rules to configure, so `true` is the honest
    /// answer to "is persistence wired up".
    ///
    /// What it does NOT promise: `...ThisDeviceOnly` items are excluded from encrypted
    /// iCloud/iTunes backups, so the id does **not** migrate to a new device. It survives
    /// delete-and-reinstall on the *same* device — best effort: a write can fail silently
    /// under a bad signing/entitlement setup, which `DeviceIDStore.persist` logs loudly
    /// (DeviceIDStore.swift:65-83), and a full device erase resets it.
    func backupRulesConfigured() throws -> Bool {
        true
    }

    // MARK: - Async failure channel

    /// Forwards an async failure to this engine's Dart side.
    ///
    /// Pigeon 29 generates `@MainActor func onError(error:) async throws`, which suspends
    /// until Dart replies. This is called from the SDK's delegate hop via
    /// `MubeenErrorRelay`; awaiting the round-trip inline would park that hop on a reply
    /// Dart cannot usefully fail. So it is launched and forgotten, which is the shape the
    /// Android side settled on (`ErrorRelay.onError` -> `main.launch { ... }`,
    /// android/.../MubeenFlutterPlugin.kt).
    ///
    /// `self` is captured rather than `flutterApi` because `MubeenFlutterApi` is not
    /// Sendable while this class is `@unchecked Sendable`; `Task {}` inside a `@MainActor`
    /// member inherits MainActor isolation, which is where `onError` must be called from.
    @MainActor
    func report(_ error: MbError) {
        if let sink = errorSink {
            sink(error)
            return
        }
        guard flutterApi != nil else { return }
        Task { [weak self] in
            guard let api = self?.flutterApi else { return }
            do {
                try await api.onError(error: error)
            } catch {
                // A channel error means the engine is gone or Dart threw; there is no
                // recovery and this must never escalate into the SDK's thread.
                NSLog("[MubeenFlutter] Dropping SDK error, engine gone? \(error)")
            }
        }
    }

    // MARK: - Error mapping

    private static func notConfiguredError() -> MbHostError {
        MbHostError(
            code: "not_configured",
            message: "configure() must be called before this method.",
            details: nil
        )
    }

    private static func unsupported(_ message: String) -> MbHostError {
        MbHostError(code: "unsupported", message: message, details: nil)
    }

    /// Maps a thrown SDK error onto the contract's code strings.
    ///
    /// The six codes the contract documents for `MbError` are
    /// not_configured / unsupported / network / rejected / rate_limited / unknown.
    /// Method throws may additionally carry `invalid_config`, `already_configured` and
    /// `disabled` (the SDK's remote kill switch), which have no async equivalent.
    ///
    /// The SDK's own `errorCode` (e.g. `MUBEEN_E_KILL_SWITCH`) is kept in the message so
    /// the coarser code string never loses support-ticket detail.
    static func hostError(from error: Error) -> MbHostError {
        if let hostError = error as? MbHostError { return hostError }

        if let sdkError = error as? MubeenSDKError {
            let code: String
            switch sdkError {
            case .notConfigured:
                code = "not_configured"
            case .configurationInvalid:
                code = "invalid_config"
            case .networkError:
                code = "network"
            case .serverError(let statusCode, _):
                if statusCode == 429 {
                    code = "rate_limited"
                } else if (500...599).contains(statusCode) {
                    code = "network"
                } else if statusCode == 404 || statusCode == 405 {
                    // The endpoint answered, but not for this route. That is a
                    // configuration problem, not a credential one, and calling it
                    // `rejected` sends the client to check an API key that is fine.
                    //
                    // Not hypothetical: on 2026-09-20 a trailing slash in the endpoint
                    // produced host//v1/mobile/fingerprint, the server answered 405, and
                    // it surfaced as MubeenAuthError. Half an hour went into the key
                    // before anyone suspected the URL. The trailing slash itself is fixed
                    // in Dart now; this keeps the NEXT routing mistake honest.
                    code = "invalid_config"
                } else if (400...499).contains(statusCode) {
                    code = "rejected"
                } else {
                    code = "unknown"
                }
            case .killSwitchActive:
                // Mubeen switched submissions off remotely. Not a key problem, so not
                // `rejected`; the Dart side documents it as a soft no-op.
                code = "disabled"
            case .keychainError, .signalCollectionFailed, .internalError,
                 .identityInitializationFailed, .attestationUnsupported,
                 .attestationFailed, .assertionFailed:
                code = "unknown"
            @unknown default:
                // MubeenSDKError ships from a binary framework, so a newer SDK can add
                // cases without a recompile here. Fall back rather than trap.
                code = "unknown"
            }
            return MbHostError(
                code: code,
                message: "\(sdkError.errorCode): \(sdkError)",
                details: nil
            )
        }

        // URLError escapes only from paths the SDK does not classify; treat as transport.
        if error is URLError {
            return MbHostError(code: "network", message: error.localizedDescription, details: nil)
        }

        return MbHostError(code: "unknown", message: error.localizedDescription, details: nil)
    }
}

/// The SDK's one, process-wide delegate, fanned out to every attached engine.
///
/// `Mubeen.delegate` is a single weak slot, so it cannot point at a plugin instance: the
/// last engine to configure would take it, and its teardown would silence every other
/// engine. This object lives for the process (`shared`), holds the plugin instances
/// weakly, and delivers each async error to all of them.
final class MubeenErrorRelay: MubeenSDKDelegate, @unchecked Sendable {

    static let shared = MubeenErrorRelay()

    private final class WeakPlugin {
        weak var plugin: MubeenFlutterPlugin?
        init(_ plugin: MubeenFlutterPlugin) { self.plugin = plugin }
    }

    /// Guards `plugins`.
    private let lock = NSLock()
    private var plugins: [ObjectIdentifier: WeakPlugin] = [:]

    func attach(_ plugin: MubeenFlutterPlugin) {
        lock.lock()
        plugins[ObjectIdentifier(plugin)] = WeakPlugin(plugin)
        lock.unlock()
    }

    func detach(_ plugin: MubeenFlutterPlugin) {
        lock.lock()
        plugins[ObjectIdentifier(plugin)] = nil
        lock.unlock()
    }

    func detachAll() {
        lock.lock()
        plugins.removeAll()
        lock.unlock()
    }

    private var attached: [MubeenFlutterPlugin] {
        lock.lock()
        defer { lock.unlock() }
        return plugins.values.compactMap { $0.plugin }
    }

    @MainActor
    func broadcast(_ error: MbError) {
        for plugin in attached {
            plugin.report(error)
        }
    }

    @MainActor
    func mubeenSDKDidSendRequest(path: String, bodySize: Int) {}

    /// The SDK's only observable delivery signal.
    ///
    /// Reported: **retryable** fingerprint failures (429 / 5xx) — exactly the cases where
    /// `sendFingerprint` returned success but nothing landed, because the SDK swallowed
    /// the error and enqueued the payload.
    ///
    /// Deliberately NOT reported: terminal 4xx, which already surface as the method's own
    /// failure; reporting them here as well would double-fire, since the delegate cannot
    /// distinguish an in-flight send from a retry drain. Known gap: a queued payload that
    /// later hits a terminal 4xx during drain is dropped silently by the SDK
    /// (MubeenDeviceSDK.swift:196) and is invisible to this channel too.
    @MainActor
    func mubeenSDKDidReceiveResponse(path: String, statusCode: Int, durationMs: Int) {
        guard let error = Self.asyncError(path: path, statusCode: statusCode) else { return }
        broadcast(error)
    }

    /// The error a response reports on the async channel, or nil for none.
    static func asyncError(path: String, statusCode: Int) -> MbError? {
        guard path == MubeenFlutterPlugin.fingerprintPath else { return nil }  // not /v1/mobile/config
        guard statusCode == 429 || (500...599).contains(statusCode) else { return nil }
        return MbError(
            code: statusCode == 429 ? "rate_limited" : "network",
            message: "Fingerprint upload returned HTTP \(statusCode); "
                + "the payload was queued for automatic retry."
        )
    }
